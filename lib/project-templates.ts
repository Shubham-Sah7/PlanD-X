function makeTasks(items: (Partial<ProgrammeTask> & {
  id: string;
  wbs: string;
  name: string;
  level: any;
  startDate: string;
  endDate: string;
  duration: number;
})[]): ProgrammeTask[] {
  return items.map((item) => ({
    parentId: null,
    assignee: null,
    notes: "",
    children: [],
    predecessors: [],
    successors: [],
    float: 0,
    isCritical: false,
    isMilestone: false,
    progress: 0,
    depth: 0,
    status: "not-started",
    trade: null,
    ...item,
  }));
}

